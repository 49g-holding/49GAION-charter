"""Generate and check the cards of [ORG]AIOC-CH, the Charter, from its blueprint.

Adapted from the card generator of the Operations Event Register mother,
github.com/49g-holding/49GAION-operations-event-register v0.1.0 (tools/make_cards.py).

The blueprint governs. This script reads the card data block of blueprint §17 (the YAML
block that starts with `parts:`) and the AIOC card of blueprint §1. It writes the complete
unit cards of every Pod and Cell into cards/, and the bot identity card of every AI Cell into
cards/bots/, as generated copies. Then it checks:
  - every unit card against spec/schemas/unit-card.schema.json of 49GAION-protocol;
  - every bot card against spec/schemas/bot-identity-card.schema.json;
  - the code rules of tests/cards/check_cards.py of 49GAION-protocol: a fixed test is never
    owned by the part itself (RULE-TEST-OWNER); a bot never claims a right to sign
    (RULE-BOT-NEVER-SIGNS); no credential is shared (RULE-CREDENTIAL-SHARED);
  - against the blueprint: the inner units of the AIOC card are exactly the parts whose
    parent is the AIOC; each Pod's inner units are exactly the Cells whose parent it is;
    the root (parent none) is accountable to its own top Cell, which carries [ORG]HOAC-GOV,
    holds the label and has no accountable_to (Standard §1.7, item 13); every Cell's fixed
    test owner is a human Cell and never the Cell itself; every accountable_to names a human
    Cell carrying a HOAC label;
  - every human Cell carries a HOAC label, and there is at least one;
  - codes: every Pod and Cell code is unique; its suffix after POD- or CELL- equals the
    initials of its full name (Naming Standard R15: words that start with a lower-case letter
    are skipped, a hyphenated word counts once, a final single capital letter counts); a Cell
    marked code_rule "R16" takes COS and the initials of the AIOC's code (Naming Standard R16,
    item 2); a Cell with any other code_rule is a recorded exception (blueprint §11), printed;
  - versions: the parts block's defaults.card_version equals the §1 card's card_version, its
    defaults.test_version equals the §1 fixed_test.version, and the §1 blueprint_version
    equals the metadata block's.
Usage: python3 tools/make_cards.py <path to 49GAION-protocol spec/schemas>   (exit 1 on any error)
"""
import json, pathlib, re, sys
import yaml, jsonschema
from referencing import Registry, Resource

ROOT = pathlib.Path(__file__).resolve().parent.parent
BP = ROOT / "blueprint" / "CH-BLUEPRINT.md"
AIOC = "[ORG]AIOC-CH"
WITHDRAWN = []  # no withdrawn codes at v0.1.0


class NoAlias(yaml.SafeDumper):
    def ignore_aliases(self, data):
        return True


HEADER = "# Generated by tools/make_cards.py from blueprint/CH-BLUEPRINT.md. The blueprint governs; do not edit by hand.\n"


def blueprint_blocks():
    text = BP.read_text(encoding="utf-8")
    meta = re.search(r"```yaml\n((?:#[^\n]*\n)*blueprint:\n.*?)```", text, re.S)
    card = re.search(r"## 1\. Card.*?```yaml\n(.*?)```", text, re.S)
    parts = re.search(r"```yaml\n(parts:\n.*?)```", text, re.S)
    if not meta or not card or not parts:
        sys.exit("cannot find the metadata block, the §1 card or the §17 parts block in the blueprint")
    return (yaml.safe_load(meta.group(1))["blueprint"], yaml.safe_load(card.group(1))["card"],
            yaml.safe_load(parts.group(1))["parts"])


def tail(code):
    """The kind and suffix of a code, without the organisation prefix: '[ORG]POD-TR' -> 'POD-TR'."""
    m = re.search(r"(AIOC|POD|CELL)-[A-Z0-9]+(-[A-Z0-9]+)?$", code or "")
    return m.group(0) if m else code


def initials(full_name):
    """Naming Standard R15: one letter per word that starts with a capital; a hyphenated word is one
    word; words that start with a lower-case letter ('of', 'and') are skipped."""
    return "".join(w[0] for w in full_name.split() if w[0].isupper())


def port(code, name, direction, kind, content, limit, trail, tests, stop=False):
    p = {"unit": code, "port": name, "direction": direction, "type": kind,
         "identification": "technical-key" if kind == "AI" else "live-human-sign-in-at-gateway",
         "accepted_content": content, "authority_limit": limit, "audit_trail": trail,
         "required_tests": tests, "enforcement": "shared-gateway-outside-unit"}
    if stop:
        p["stop_door"] = True
    return p


def unit_card(entry, kind, d):
    code = entry["code"]
    test = entry["test"]
    tests = [f"{test['id']} {d['test_version']}"]
    trail = d["audit_trail"]
    card = {"unit_kind": kind, "code": code, "full_name": entry["full_name"],
            "parent": entry.get("parent", AIOC),
            "accountable_to": entry.get("accountable_to", d["accountable_to"]),
            "type": entry["type"], "card_version": d["card_version"], "version": d["version"],
            "lineage": {"id": code, "version": d["version"], "relation": "original"},
            "lifecycle_state": d["lifecycle_state"],
            "fixed_test": {"id": test["id"], "version": d["test_version"], "owner": test.get("owner", d["test_owner"])}}
    if card["accountable_to"] is None:
        del card["accountable_to"]          # only the Cell carrying the unscoped [ORG]HOAC-GOV
    if kind == "CELL":
        card["filler_kind"] = entry["filler_kind"]
    for k in ("hoac", "entity", "authority_scope", "inner_units", "top_cell"):
        if k in entry:
            card[k] = entry[k]
    role = "as in its role card (blueprint §4-§5)"
    ports = [
        port(code, "ai-in", "input", "AI", entry["ai_in"], role, trail, tests),
        port(code, "ai-out", "output", "AI", entry["ai_out"], role, trail, tests),
        port(code, "hu-in", "input", "HU", entry.get("hu_in", d["hu_in"]), "the signer's authority_scope; nothing received here is a source", trail, tests),
        port(code, "hu-out", "output", "HU", entry.get("hu_out", d["hu_out"]), "information only", trail, tests),
    ]
    for x in entry.get("external_ports", []):
        ports.append(port(code, x["port"], x["direction"], "AI", x["accepted_content"], x["authority_limit"], x["audit_trail"], tests))
    ports.append(port(code, "stop", "input", "HU", ["stop"], "stop only", "unit register", tests, stop=True))
    card["ports"] = ports
    return card


SEATS = {"[ORG]CELL-TMS": "[ORG]HOAC-TM (top management, [ORG]CELL-TMS)",
         "[ORG]CELL-GK": "[ORG]HOAC-ACS (the Gateway Keeper, [ORG]CELL-GK)"}


def bot_card(entry, dflt):
    code = entry["code"]
    cred = "cred-" + re.sub(r"[^a-z0-9]+", "-", code.lower().replace("[org]", "org-")).strip("-")
    return {"bot": f"{code} bot", "aioc": AIOC, "role": f"Fills {code} ({entry['role']}); role card in blueprint/CH-BLUEPRINT.md",
            "account": {"id": cred, "separate": True},
            "allowed_actions": entry["bot"]["allowed_actions"], "ask_first_actions": entry["bot"]["ask_first_actions"],
            "accountable_human_position": SEATS.get(entry.get("accountable_to", dflt["accountable_to"]), "none: not a human seat"),
            "card_version": "v3", "status": "DRAFT",
            "credential": {"id": cred, "holder": code, "shared": False},
            "cell_kind": entry.get("cell_kind", "ai-cell"), "never_signs": True, "memory_on_filler_change": "sealed"}


def slug(code):
    return re.sub(r"[^a-z0-9]+", "-", code.lower().replace("[org]", "org-")).strip("-")


def main(schema_dir):
    d = pathlib.Path(schema_dir)
    resources = []
    for f in d.glob("*.schema.json"):
        doc = json.loads(f.read_text(encoding="utf-8"))
        res = Resource.from_contents(doc)
        resources += [(doc["$id"], res), (f.name, res)]
    reg = Registry().with_resources(resources)
    uv = jsonschema.Draft202012Validator(json.loads((d / "unit-card.schema.json").read_text()), registry=reg)
    bv = jsonschema.Draft202012Validator(json.loads((d / "bot-identity-card.schema.json").read_text()), registry=reg)

    meta, aioc, parts = blueprint_blocks()
    dflt = parts["defaults"]
    entries = [("CELL", e) for e in parts["cells"]] + [("POD", e) for e in parts["pods"]]
    units = {}
    for kind, e in entries:
        units[e["code"]] = unit_card(e, kind, dflt)
    bots = {e["code"]: bot_card(e, dflt) for e in parts["cells"] if e["filler_kind"] == "ai"}

    out, bout = ROOT / "cards", ROOT / "cards" / "bots"
    bout.mkdir(parents=True, exist_ok=True)
    for f in list(out.glob("*.card.yaml")) + list(bout.glob("*.yaml")):
        f.unlink()
    for code, c in units.items():
        (out / f"{slug(code)}.card.yaml").write_text(HEADER + yaml.dump(c, Dumper=NoAlias, sort_keys=False, allow_unicode=True), encoding="utf-8")
    for code, b in bots.items():
        (bout / f"{slug(code)}.bot-identity-card.yaml").write_text(HEADER + yaml.dump(b, Dumper=NoAlias, sort_keys=False, allow_unicode=True), encoding="utf-8")

    errors = []
    for code, c in {**units, AIOC: aioc}.items():
        errors += [f"{code}: {e.message}" for e in uv.iter_errors(c)]
        if (c.get("fixed_test") or {}).get("owner") == c.get("code"):
            errors.append(f"{code}: RULE-TEST-OWNER (a fixed test is never owned by the part itself)")
    for code, b in bots.items():
        errors += [f"{code} bot: {e.message}" for e in bv.iter_errors(b)]
        if any(re.search(r"\bsign", a, re.I) for a in b["allowed_actions"]):
            errors.append(f"{code} bot: RULE-BOT-NEVER-SIGNS")
    creds = [b["credential"]["id"] for b in bots.values()]
    if len(creds) != len(set(creds)):
        errors.append("RULE-CREDENTIAL-SHARED: a credential id is used twice")
    # consistency with the blueprint
    direct = sorted(k for k, c in units.items() if c["parent"] == AIOC)
    if sorted(aioc.get("inner_units", [])) != direct:
        errors.append(f"AIOC inner_units {sorted(aioc.get('inner_units', []))} != parts whose parent is the AIOC {direct}")
    for k, c in units.items():
        if c["unit_kind"] == "POD":
            kids = sorted(x for x, y in units.items() if y["parent"] == k)
            if sorted(c.get("inner_units", [])) != kids:
                errors.append(f"{k}: inner_units {sorted(c.get('inner_units', []))} != Cells whose parent is it {kids}")
            if c.get("top_cell") not in kids:
                errors.append(f"{k}: top_cell is not a Cell of the Pod")
        owner = c["fixed_test"]["owner"]
        if owner in units and units[owner].get("filler_kind") != "human":
            errors.append(f"{k}: fixed test owner {owner} is not a human Cell")
    # every human position is a HOAC position (49GAION/DR-0011, DR-0013)
    humans = [k for k, c in units.items() if c.get("filler_kind") == "human"]
    if not humans:
        errors.append("no HOAC position: the AIOC has at least one human Cell carrying a HOAC label")
    for k in humans:
        if not units[k].get("hoac"):
            errors.append(f"{k}: a human Cell with no HOAC label; every human position is a HOAC position")
    # the root (Standard §1.7, item 13; Protocol §23, item 1)
    if aioc.get("parent") != "none":
        errors.append("the Charter's parent is not none")
    gov = aioc.get("top_cell")
    if aioc.get("accountable_to") != gov or gov not in units:
        errors.append("the Charter is not accountable to its own top Cell")
    elif units[gov].get("hoac") != "[ORG]HOAC-GOV" or "accountable_to" in units[gov] or units[gov].get("filler_kind") != "human":
        errors.append(f"{gov}: the top Cell is not the human Cell carrying [ORG]HOAC-GOV with no accountable_to")
    elif "entity" in units[gov] or "entity" in (units[gov].get("authority_scope") or {}):
        errors.append(f"{gov}: the Cell carrying [ORG]HOAC-GOV in the Charter is unscoped")
    roots = [k for k, c in units.items() if "accountable_to" not in c]
    if roots != [gov]:
        errors.append(f"only the GOV Cell has no accountable_to; found {roots}")
    if aioc.get("label_holder") != gov or aioc.get("hoac") != "[ORG]HOAC-GOV":
        errors.append("the Charter's label is [ORG]HOAC-GOV, held by its top Cell")
    for k, c in units.items():
        a = c.get("accountable_to")
        if a and (a not in units or units[a].get("filler_kind") != "human" or not units[a].get("hoac")):
            errors.append(f"{k}: accountable_to {a} is not a human Cell carrying a HOAC label (CHAIN-TARGET)")
    # codes: unique, R15 initials, never a withdrawn code
    codes = [e["code"] for _, e in entries]
    for code in sorted({c for c in codes if codes.count(c) > 1}):
        errors.append(f"{code}: the code is used by {codes.count(code)} parts; codes are unique across Pods and Cells")
    aioc_initials = tail(AIOC).split("-", 1)[1]
    for kind, e in entries:
        suffix = tail(e["code"]).split("-", 1)[1]
        rule = e.get("code_rule", "R15")
        if rule == "R16":
            if suffix != "COS" + aioc_initials:
                errors.append(f"{e['code']}: R16: the suffix {suffix} is not COS{aioc_initials}")
            if e.get("role") != "Chief of Staff":
                errors.append(f"{e['code']}: R16 applies only to a Chief of Staff Cell")
        elif rule != "R15":
            print(f"EXCEPTION {e['code']}: {rule}")
        elif suffix != initials(e["full_name"]):
            errors.append(f"{e['code']}: R15: the suffix {suffix} is not the initials {initials(e['full_name'])} of '{e['full_name']}'")
    named = set(codes) | {aioc.get(k) for k in ("code", "top_cell", "label_holder", "accountable_to")} | set(aioc.get("inner_units", []))
    for c in units.values():
        named |= {c.get("parent"), c.get("accountable_to"), c.get("top_cell"), c["fixed_test"]["owner"], *c.get("inner_units", [])}
    for code in sorted(x for x in named if x and tail(x) in {tail(w) for w in WITHDRAWN}):
        errors.append(f"{code}: a withdrawn code (blueprint §17); it is never issued again")
    # versions
    if dflt.get("card_version") != aioc.get("card_version"):
        errors.append(f"defaults.card_version {dflt.get('card_version')} != the §1 card_version {aioc.get('card_version')}")
    if dflt.get("test_version") != (aioc.get("fixed_test") or {}).get("version"):
        errors.append(f"defaults.test_version {dflt.get('test_version')} != the §1 fixed_test.version {(aioc.get('fixed_test') or {}).get('version')}")
    if aioc.get("blueprint_version") != meta.get("blueprint_version"):
        errors.append(f"the §1 blueprint_version {aioc.get('blueprint_version')} != the metadata blueprint_version {meta.get('blueprint_version')}")

    for e in errors:
        print("INVALID", e)
    print(f"{len(units)} unit cards and {len(bots)} bot identity cards written; AIOC card checked; {len(errors)} errors")
    return 1 if errors else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1]))
